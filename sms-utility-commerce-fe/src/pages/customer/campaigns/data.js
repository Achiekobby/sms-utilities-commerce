// Illustrative history matching the dashboard, until the campaigns API is connected.
// `delivered`, `pending`, and `failed` are omitted when delivery has not been reported.

function history({ messages, rate, failedShare = 0.6 }) {
  const delivered = Math.round(messages * rate)
  const rest = messages - delivered
  const failed = Math.round(rest * failedShare)
  return { recipients: messages, segments: 1, delivered, failed, pending: rest - failed }
}

