// Illustrative campaigns until the campaigns API is connected.
// Delivery fields are omitted when a campaign has not sent yet.

function history({ messages, rate, failedShare = 0.6 }) {
  const delivered = Math.round(messages * rate)
  const rest = messages - delivered
  const failed = Math.round(rest * failedShare)
  return {
    recipients: messages,
    segments: 1,
    sent: messages,
    delivered,
    failed,
    pending: rest - failed,
  }
}

